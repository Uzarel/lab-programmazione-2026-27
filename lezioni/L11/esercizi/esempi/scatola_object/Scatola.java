/** Contiene un oggetto qualsiasi. */
public class Scatola {

    private Object contenuto;

    public Scatola(Object contenuto) {
        this.contenuto = contenuto;
    }

    public Object getContenuto() {
        return contenuto;
    }

    public void setContenuto(Object contenuto) {
        this.contenuto = contenuto;
    }
}
